from aiogram import Router, F
from aiogram.types import Message

router = Router()

@router.message(F.text.in_({"راهنما", "/help", "❓ راهنما"}))
async def show_help_menu(message: Message):
    help_text = (
        "「 🎰 **میوبت** 」\n\n"
        "🎲 **شرط‌بندی تاس:** کلمه شرط با # شروع میشه، مثلا:\n"
        "`#زوج 20کی میو` → ۲۰٬۰۰۰ روی زوج\n"
        "`#فرد 2000 میو` → ۲٬۰۰۰ روی فرد\n\n"
        "⚔️ **دوئل:** با دستور میوبت بازی ۱ در ۱ شروع کن، مثلا:\n"
        "`میوبت تاس 50کی` → دوئل تاس با ۵۰٬۰۰۰\n"
        "🪙 **حق میز:** ۵٪ از جایزه کسر میشه\n\n"
        "💩 **بازی پوپ:** بازی شانسی ۵ مرحله‌ای، مثلا:\n"
        "`#پوپ 100کی` → شروع بازی با ۱۰۰٬۰۰۰\n"
        "💰 **ضرایب:** ×1.2 → ×1.5 → ×2.0 → ×3.0 → ×4.0\n\n"
        "✌️ **سنگ کاغذ قیچی:**\n"
        "`#سنگ [مبلغ]` یا `#کاغذ [مبلغ]` یا `#قیچی [مبلغ]`\n\n"
        "🃏 **بازی بلک‌جک (۲۱):**\n"
        "`#بلکجک [مبلغ]` برای شروع بازی کارت\n\n"
        "🎯 **راهنمای کاربر:**\n"
        "💰 **موجودی** → نمایش موجودی\n"
        "💳 **شارژ** → توی پیوی ربات بفرست تا موجودی اضافه کنی\n"
        "💸 **برداشت** → توی پیوی ربات بفرست تا موجودی برداشت کنی\n"
        "❓ **راهنما** → نمایش این راهنما\n\n"
        "🎲 بعد از ثبت شرط ۳ تاس 🎲 بفرست (نه فوروارد!).\n"
        "اگر نفرستی یا تاس فوروارد کنی جریمه میشی.\n"
        "با دکمه لغو شرط قبل از اولین تاس میتونی شرطت رو بدون جریمه لغو کنی."
    )
    await message.reply(help_text, parse_mode="Markdown")
