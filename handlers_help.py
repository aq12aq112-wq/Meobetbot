from aiogram import Router, F
from aiogram.types import Message

router = Router()

@router.message(F.text.in_({"راهنما", "/help", "❓ راهنما"}))
async def show_help_menu(message: Message):
    help_text = (
        "📖 **راهنمای جامع ربات میوبت (MEOWBET)**\n\n"
        "💳 **واحد پول تمام بازی‌ها و تراکنش‌ها میو (MEOW) است.**\n"
        "• برای چک کردن موجودی بنویسید: `موجودی`\n\n"
        "🎲 **۱. بازی زوج و فرد (تاس دستی):**\n"
        "• دستور: `#زوج [مبلغ]` یا `#فرد [مبلغ]`\n"
        "• پس از ارسال دستور، ربات از شما می‌خواهد **۳ بار** تاس 🎲 (دستی) بفرستید تا مجموع آن‌ها محاسبه شود.\n\n"
        "✌️ **۲. بازی سنگ کاغذ قیچی:**\n"
        "• دستور: `#سنگ [مبلغ]` یا `#کاغذ [مبلغ]` یا `#قیچی [مبلغ]`\n\n"
        "💩 **۳. بازی پوپ مرحله‌ای:**\n"
        "• دستور: `#پوپ [مبلغ]`\n"
        "• چیدمان پپ‌ها در ۵ مرحله: (۱، ۱، ۲، ۲ و ۳ پوپ) به همراه ضرایب صعودی ×1.2 تا ×4.0\n\n"
        "💡 *نکته:* تمام بازی‌ها فقط در **گروه‌ها** قابل اجرا هستند."
    )
    await message.reply(help_text, parse_mode="Markdown")
