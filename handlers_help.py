from aiogram import Router, F
from aiogram.types import Message

router = Router()

@router.message(F.text.in_({"راهنما", "/help", "❓ راهنما"}))
async def show_help_menu(message: Message):
    help_text = (
        "📖 **راهنمای جامع و دستورات بازی‌های میوبت (MEOWBET)**\n\n"
        "💳 واحد پول تمام بازی‌ها **میو (MEOW)** است.\n"
        "• برای چک کردن موجودی خود، کلمه `موجودی` را ارسال کنید.\n\n"
        "----------------------------------\n"
        "🎲 **۱. بازی تاس (زوج و فرد):**\n"
        "• **نحوه بازی:** ابتدا در گروه بنویسید `#زوج [مبلغ]` یا `#فرد [مبلغ]`\n"
        "  *(مثال: `#زوج 50k` یا `#فرد 10000`)*\n"
        "• سپس ربات از شما می‌خواهد **۳ بار تاس** 🎲 دستی بفرستید.\n"
        "• پس از فرستادن ۳ تاس، مجموع آن‌ها محاسبه شده و اگر درست پیش‌بینی کرده باشید، جفت‌وجور پولت برنده میشه!\n\n"
        "✌️ **۲. بازی سنگ، کاغذ، قیچی:**\n"
        "• **نحوه بازی:** دستور را به همراه مبلغ در گروه بفرستید:\n"
        "  • `#سنگ 20k`\n"
        "  • `#کاغذ 20k`\n"
        "  • `#قیچی 20k`\n\n"
        "💩 **۳. بازی پوپ مرحله‌ای:**\n"
        "• **نحوه بازی:** بنویسید `#پوپ [مبلغ]` *(مثال: `#پوپ 50000`)*\n"
        "• بازی دارای ۵ مرحله با ضرایب صعودی (×1.2 تا ×4.0) است.\n"
        "• تعداد پپ‌ها در مراحل: ردیف ۱ و ۲ (۱ پپ)، ردیف ۳ و ۴ (۲ پپ)، ردیف ۵ (۳ پپ).\n\n"
        "💡 *نکته مهم:* تمام بازی‌ها فقط در **گروه‌ها** قابل اجرا هستند."
    )
    await message.reply(help_text, parse_mode="Markdown")

